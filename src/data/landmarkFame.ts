/**
 * ★ 4A 的**平台热度**到多少就算「全国知名」。
 *
 * ⚠️ 这**不是**在说「热度 = 知名度」（那是两件事，见 `types.ts` 的注释）——
 *    只是「有人点评打卡」是「全国都有人去」的一个**可用代理**：
 *    4A 里热度最高的那些（成都大熊猫繁育研究基地 9.6、三星堆博物馆 9.1、
 *    广州塔 8.6、茶卡盐湖 8.6）确实条条都是全国叫得响的。
 *
 * ⚠️ 实测分布（991 条有热度的 4A）：p50 = 6.3、p75 = 5.9、max = 9.6。
 *    取 8.5 大约命中**最热的那 25 条上下**，是个刻意保守的阈值 ——
 *    宁可漏（漏的会落到「地方知名」，家长在复核页上一眼能看见），
 *    不可滥（滥了「全国知名」就失去意义）。
 */
export const NATIONAL_HEAT = 8.5

const WORLD_SET = new Set(WORLD_FAMOUS)
const NATIONAL_SET = new Set(NATIONAL_EXTRA)

/** 判一条地标的知名度。★ 全库每条都会拿到一个值，不会返回 undefined。 */
export function fameOf(seed: {
  id: string
  rating?: '5A' | '4A'
  heat?: number
}): LandmarkFame {
  if (WORLD_SET.has(seed.id)) return '世界知名'
  if (seed.rating === '5A') return '全国知名'
  if (seed.id.startsWith('world-')) return '全国知名'
  if (NATIONAL_SET.has(seed.id)) return '全国知名'
  if (typeof seed.heat === 'number' && seed.heat >= NATIONAL_HEAT) return '全国知名'
  return '地方知名'
}
