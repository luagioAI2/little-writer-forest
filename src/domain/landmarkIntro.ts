/* ============================================================
   「景点公共简介」的字数上限 —— **这个数字唯一的家**
   ============================================================

   什么是"公共简介"：挂在**地标**上的一段话，属于这个景点本身 ——
   不是某一张图自己的 `summary`（那句 ≤60 字），也不是某一篇 `essay`。
   同一个景点不管配了几张图，简介**只有一条**，编辑器与 App 读的是同一份
   （数据在 `src/data/landmark-intros.json`）。

   ------------------------------------------------------------
   ★★ 为什么这一个数字要单独一个文件（不是"过度拆分"，是躲一个真实的坑）

     `vite.config.ts` 的 tsconfig 是 `moduleResolution: nodenext`，
     相对导入**必须带扩展名**。从它引 `src/domain/types.ts` 会把 `types.ts`
     也拉进 node 那个 tsconfig，而 `types.ts` 自己那句
     `import type { CharacterSpec } from './character'` **不带扩展名**
     → 直接 TS2835 报错（实测：`npm run lint` 红在这一行）。

     ➜ 把数字挪到一个**自己不 import 任何东西**的小文件里：
       `vite.config.ts` 和 `src/` 两边都能引，而定义**仍然只有一份**。

   ⚠️ 别为了省一个文件把它抄成两份 —— 抄两份就会出现
      "编辑器说没超、落盘端点却拒收"这种自相矛盾，而**两边都不报错**。

   ------------------------------------------------------------
   ★★ 三个判定点，都读这个常量（少一处 = 那条路能悄悄存进一条超长简介）

     ① `src/data/landmarkIntros.test.ts` —— 盘上每条必须 ≤ 它（数据侧）
     ② `travel-editor.html` 的计数与体检       —— 打字时当场变红（界面侧）
     ③ `vite.config.ts` 的 `/__save-landmark-intros` —— 超了**拒收**（落盘侧）
        ⚠️ 是**拒收**不是截断：截断是静默的，家长以为存进去了、
           尾巴其实被砍掉，界面上看不出任何区别。

   ⚠️ 计数口径是 `String.length`（**含标点**），跟编辑器里散文那个计数一致。
      换成"只数汉字"会让同一个数字在三个地方算出三个结果。
   ============================================================ */

export const LANDMARK_INTRO_MAX = 300
