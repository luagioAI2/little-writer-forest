/* ============================================================
   A 级景区「名字」的规范化与匹配 —— **只有这一份**
   ============================================================

   ★★ 为什么单独一个文件：这个判定有**两个调用方** ——
     · `fetch-a-level-cn.mjs`  —— 给 5A 捞坐标（拿文旅部的名字去站上找同一条）
     · `build-landmarks-cn.mjs` —— 把官方 1357 条与手工/GD 那 265 条合并去重
   两处各写一遍的话，改了一处忘了另一处 —— 表现是"去重结果和坐标结果对不上"，
   **不报错**，只有把两份数据摆在一起才看得出来（见 MEMORY §四「同一个判定只许有一个函数」）。

   ------------------------------------------------------------
   规范化（`normLandmarkName`）

     两件事：① 去掉分隔符与空格 ② **反复**剥掉末尾的通用后缀。
       `岳麓山-橘子洲旅游区` → `岳麓山橘子洲`
       `黄山风景区`           → `黄山`
       `西溪国家湿地公园`     → `西溪国家`
     反复剥是必须的：`风景名胜区` 剥掉后可能还剩 `国家`… 但**不许把「国家」当中缀删** ——
     它出现在 `国家森林公园` 里本来就是后缀的一部分。

     ⚠️⚠️ **`风景区` / `游览区` 曾经漏在表外**，代价是两处都错：
       · 坐标：`黄山风景区` 归一成 `黄山风景`，跟文旅部的 `黄山` 对不上
       · 去重：手工的 `西湖`/`黄山`/`青海湖`/`天涯海角` 认不出官方那条 → **库里同一个地方两条**
     加上这两个后缀后，去重正确数 12→15、GD 20→21，而坐标命中数**不变**（335）。
     ➜ 教训：**后缀表漏一个，就是整类 100% 失败**（同 MEMORY §六）。

   ------------------------------------------------------------
   匹配（`containScore`）

     ★★ 判据是「**短的那个被长的完全包含**」，**不是**最长公共子串。
       LCS 会认下这些：`乔家大院景区`⇐`山西王家大院`、`城墙•碑林历史文化景区`⇐`终南山古楼观历史文化景区`
       —— 共的只是「大院」「历史文化景区」这种**通用词**，看着完全合理、不报错。
     包含关系保守且够用：`乌镇`⊂`乌镇古镇` ✓   `西湖`⊂`杭州西湖` ✓   `乔家大院`⊄`王家大院` ✗

     ⚠️ 试过放宽到「公共子串 ≥3 字且占比 ≥50%」，**第一条就翻车**：
       `环球恐龙城休闲旅游区` ⇐ `南京游子山休闲旅游区`（只共「休闲旅游区」）➜ 所以不放宽。

   ⚠️⚠️ **包含关系只适合"在池子里找同一条"（坐标），不适合"判断两个名字是不是同一个地方"（去重）。**
     实测：`上海外滩`⊂`上海博物馆`？不是。但 `张家界`⊂`张家界大峡谷` ✓、`西双版纳`⊂`中科院西双版纳热带植物园` ✓
     —— 后两个都是**错**的（两个不同的地方）。所以：
       · 坐标可以接受「同一片景区的另一个部件」（点就在附近，误差几十公里以内）
       · 去重**只认归一后完全相等**（`normLandmarkName(a) === normLandmarkName(b)`），
         另加**同省**限制 —— 不加省份限制的话 `西湖` 会撞上扬州的 `瘦西湖风景区`。
   ============================================================ */

/** 末尾的通用后缀 —— **反复**剥，直到不再变化。
 *  ⚠️ 顺序不影响结果（是 do/while 反复剥），但**长的写在前面**便于人读。
 *  ⚠️ 加新后缀前先问：**它会不会让两个不同的地方归一成同一个名字？**
 *     例如「古镇」就不该加 —— `西塘古镇` 与 `南浔古镇` 去掉后是 `西塘`/`南浔`，还行；
 *     但 `青岩古镇` 与 `青岩寺` 会变成 `青岩`/`青岩寺`… 总之**加之前先量一遍**。 */
const SUFFIX =
  /(旅游景区|旅游度假区|生态旅游区|旅游区|风景名胜区|风景区|游览区|国家级风景区|国家森林公园|森林公园|国家遗址公园|遗址公园|国家地质公园|地质公园|湿地公园|自然保护区|文化景区|度假区|博物院|博物馆|植物园|廊道|景区)$/

/** 规范化一个景区名：去分隔符/空格 → 反复剥后缀。 */
export function normLandmarkName(s) {
  let t = String(s).replace(/[·•\-－—–\s（）()]/g, '')
  let prev
  do {
    prev = t
    t = t.replace(SUFFIX, '')
  } while (t !== prev)
  return t
}

/** 包含关系打分：**短的那个被长的完全包含**才算命中，分数 = 短名长度（越长越具体）。
 *  `100` = 完全相等。`0` = 不认。 */
export function containScore(a, b) {
  if (a === b) return 100
  if (a.length < 2 || b.length < 2) return 0
  if (b.includes(a)) return a.length
  if (a.includes(b)) return b.length
  return 0
}

/* ============================================================
   判据二：「这两个名字是不是**同一个景区**」（去重用）
   ============================================================

   ⚠️⚠️ 跟上面的 `containScore` **不是一回事**，别互相顶替：
     · `containScore`（包含关系）宽松 —— 用来**在池子里找同一条**（捞坐标）。
       它会把 `张家界` 认成 `张家界大峡谷` 的一部分，而那是**两个不同的地方**。
     · `sameScenicArea`（下面这个）严格 —— 用来**判断重复**。
       要求「核心名相同，或短的整个是长的前缀、多出来的那截只是景区套话」。

   ★★ 这套判据**原本只活在单元测试里**（`landmarks.test.ts` 的「同一个景区在同一市里
      不许有重影」那条），因为当时脚本是 .mjs、import 即执行、测试引不进来。
      现在它搬到这里，**生成侧和守卫共用同一份** ——
      否则生成侧按 A 规则去重、守卫按 B 规则检查，结果就是"生成说没有重影、测试说有"。

   ⚠️ **必须由调用方保证"同一个市"** —— 名字相同的「莲花山」在广东有好几座
      （番禺/东莞/惠州/江门/汕头…），不加市限制会把它们并成一条。
   ============================================================ */

/** 名字里"只是套话"的部分 —— 核心名 = 去掉这些之后剩下的。
 *  ⚠️ 是**全局无锚点**替换（不是只剥末尾）：`观音山旅游风景区` → `观音山`。 */
const SCENIC_TAIL_RE = /旅游度假区|风景名胜区|文化旅游区|旅游景区|旅游区|风景区|度假区|景区|旅游|文化|国际|国家/g

/** 核心名相等时，**多出来的那截**必须是这里面的一个，才算"只是套话不同"。
 *  ⚠️ 收紧成"只认一个景区后缀"是**故意的**：放宽成"任意套话"会把
 *     `长隆欢乐世界` / `长隆飞鸟乐园` 也并掉 —— 那是**四个不同的园**
 *     （各自的票、各自的一天），不是重影。 */
const SCENIC_SUFFIX_ONLY =
  /^(旅游区|旅游景区|风景区|风景名胜区|旅游度假区|文化旅游区|景区|公园|森林公园|国家森林公园|地质公园|世界地质公园|水库|温泉|旅游风景区|生态旅游区)$/

/** 去掉括号注释、开头的「XX市/省」、以及套话，得到"这是哪儿"。
 *  例：`苏州园林（拙政园－留园－虎丘）` → `苏州园林`；`丹霞山景区` → `丹霞山`。 */
export function coreScenicName(name) {
  return String(name)
    .replace(/[（(].*?[）)]/g, '')
    .replace(/^[\u4e00-\u9fa5]{2,3}[市省]/, '')
    .replace(SCENIC_TAIL_RE, '')
    .replace(/\s+/g, '')
}

/** 两个名字是不是**同一个景区**。调用方负责保证「同一个市」。
 *  ⚠️ 短核心必须 ≥3 字 —— 2 字的（`西湖`/`泰山`）太容易撞。 */
export function sameScenicArea(a, b) {
  const ca = coreScenicName(a)
  const cb = coreScenicName(b)
  if (ca.length < 3 || cb.length < 3) return false
  if (ca === cb) return true // 核心名一模一样 = 就是同一个景区（只是全名写法不同）
  const [long, short] = ca.length >= cb.length ? [ca, cb] : [cb, ca]
  return long.startsWith(short) && SCENIC_SUFFIX_ONLY.test(long.slice(short.length))
}
