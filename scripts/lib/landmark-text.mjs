const FALLBACK_BLURB = '是个值得停下来看看的地方。'

/** 稳定哈希 —— 同一个 id 永远选到同一条变体，重跑不会让文案乱跳 */
function hash(s) {
  let h = 2166136261
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return Math.abs(h)
}

/** 按 id 稳定地从一组变体里选一条 */
export function pickVariant(list, id) {
  return list[hash(id) % list.length]
}

/** 按 scene 取一句话介绍。`scene` 不认识 → 通用兜底句。 */
export function blurbForScene(scene, id) {
  const list = BLURB_BY_SCENE[scene]
  return list ? pickVariant(list, id) : FALLBACK_BLURB
}
