# 半角逗号会撞上「文案里没有半角逗号」那条守卫
for tag, items in NEW.items():
    for title, lead in items:
        for s, what in ((title, '标题'), (lead, '引导语')):
            assert ',' not in s, f'{tag} 的{what}里有半角逗号：{s}'
            assert "'" not in s, f'{tag} 的{what}里有单引号，会截断字符串：{s}'
            assert s == s.strip(), f'{tag} 的{what}首尾有空白'

with io.open(SRC, 'r', encoding='utf-8', newline='') as f:
    raw = f.read()

assert '\n' not in raw.replace('\r\n', ''), '文件里混了 LF-only 行尾，先别动'
lines = raw.split('\r\n')

# 先算出每个标签的插入点（闭合 `  ],` 的行号），再**从后往前**插，避免下标漂移
plan: list[tuple[int, list[str]]] = []
seen: set[str] = set()
for i, line in enumerate(lines):
    # ⚠️ 带连字符的键在 TS 里**必须加引号**（`'home-scene': [`）——
    #    只写 `[A-Za-z-]+` 会漏掉 11 个标签，而且不报错，只是"找不到"。
    m = re.match(r"^  '?([A-Za-z-]+)'?: \[$", line)
    if not m:
        continue
    tag = m.group(1)
    if tag not in NEW:
        continue
    # 找这个块自己的闭合行：从下一行起，第一个恰好是 `  ],`
    for j in range(i + 1, len(lines)):
        if lines[j] == '  ],':
            break
    else:
        sys.exit(f'标签 {tag} 找不到闭合行')
    block = NEW[tag]
    new_lines = [
        "    { title: '%s', lead: '%s', scenes: [PHOTO_SLOT] }," % (t, l)
        for t, l in block
    ]
    plan.append((j, new_lines))
    seen.add(tag)

missing = set(NEW) - seen
assert not missing, f'这些标签没在文件里找到：{sorted(missing)}'
assert len(plan) == 42, f'只找到 {len(plan)} 个标签块'

for j, new_lines in sorted(plan, key=lambda p: -p[0]):
    lines[j:j] = new_lines

out = '\r\n'.join(lines)
with io.open(SRC, 'w', encoding='utf-8', newline='') as f:
    f.write(out)

print(f'已插入 {total_new} 条，涉及 {len(plan)} 个标签')
